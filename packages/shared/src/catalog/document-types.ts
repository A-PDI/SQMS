/**
 * Seed catalog of the 37 SQMS document and record types.
 *
 * Identifiers (codes) are preserved exactly from the company document catalog.
 * `origin` distinguishes company-defined templates from externally standardized artifacts:
 *   - COMPANY_DEFINED: company form; its name is not mandated by any external standard.
 *   - EXTERNAL_STANDARD: the artifact is defined by an external reference (e.g. AIAG PPAP element).
 *   - COMPANY_DEFINED_STANDARD_ALIGNED: company form that can be prepared in a standard-aligned format when required.
 *
 * Retention policies reference policy codes whose periods are intentionally left undefined (null) until the
 * company defines them; the system does not invent legal retention periods.
 * All of this metadata is editable by administrators at runtime.
 */

export type DocumentCategoryCode =
  | "INTAKE"
  | "SUPPLIER_ONBOARDING"
  | "ENGINEERING"
  | "VALIDATION"
  | "OPERATIONS"
  | "GOVERNANCE";

export type DocumentOrigin = "COMPANY_DEFINED" | "EXTERNAL_STANDARD" | "COMPANY_DEFINED_STANDARD_ALIGNED";
export type SupplierVisibilityCode = "INTERNAL_ONLY" | "SUPPLIER_VIEW_RELEASED" | "SUPPLIER_CONTRIBUTE";
export type PathwayCode = "A" | "B" | "C";

export interface DocumentTypeSeed {
  code: string;
  name: string;
  acronym: string | null;
  category: DocumentCategoryCode;
  origin: DocumentOrigin;
  externalStandardRef: string | null;
  description: string;
  purpose: string;
  responsibleDepartment: string;
  typicalPreparer: string;
  workflowKey: string;
  applicablePathways: PathwayCode[];
  applicabilityConditions: string;
  riskRuleSummary: string;
  ownerRoleKey: string;
  approvalRequirements: string;
  approverRoleKeys: string[];
  retentionPolicyCode: string;
  supplierVisibility: SupplierVisibilityCode;
  instructions: string;
  nativeFormKey: string | null;
  nativeModule: string | null;
  allowUpload: boolean;
}

