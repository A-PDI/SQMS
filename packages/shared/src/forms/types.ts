/**
 * Native form schema format. Schemas are stored as JSON in form_definition_versions and are immutable once
 * published; every submission records the exact schema version used.
 */

export interface FieldOption {
  value: string;
  label: string;
}

/** Visibility condition referencing another field in the same form (top-level key or same-row column). */
export interface VisibleWhen {
  field: string;
  equals?: string | number | boolean;
  in?: (string | number | boolean)[];
  notEmpty?: boolean;
}

interface BaseField {
  key: string;
  label: string;
  help?: string;
  required?: boolean;
  visibleWhen?: VisibleWhen;
  /** Field rendered read-only (e.g. values generated by the system). */
  readOnly?: boolean;
}

export interface TextField extends BaseField {
  type: "text" | "textarea" | "email" | "url";
  minLength?: number;
  maxLength?: number;
  placeholder?: string;
}

export interface NumberField extends BaseField {
  type: "number";
  min?: number;
  max?: number;
  integer?: boolean;
  unit?: string;
}

export interface DateField extends BaseField {
  type: "date";
}

export interface SelectField extends BaseField {
  type: "select" | "radio";
  options: FieldOption[];
}

export interface MultiSelectField extends BaseField {
  type: "multiselect";
  options: FieldOption[];
  minItems?: number;
}

export interface CheckboxField extends BaseField {
  type: "checkbox";
}

export interface AttachmentField extends BaseField {
  type: "attachment";
  multiple?: boolean;
}

export type ScalarField = TextField | NumberField | DateField | SelectField | MultiSelectField | CheckboxField;

export interface TableField extends BaseField {
  type: "table";
  columns: ScalarField[];
  minRows?: number;
  maxRows?: number;
}

export type FormField = ScalarField | AttachmentField | TableField;

/** Authoring-time reference to a reusable field from the field library (resolved before storage). */
export interface FieldRef {
  ref: string;
  overrides?: Partial<Omit<FormField, "type">> & { key?: string };
}

export interface FormSection {
  key: string;
  title: string;
  description?: string;
  visibleWhen?: VisibleWhen;
  fields: FormField[];
}

export interface FormSchema {
  key: string;
  title: string;
  description?: string;
  sections: FormSection[];
}

export interface AuthoringSection extends Omit<FormSection, "fields"> {
  fields: (FormField | FieldRef)[];
}

export interface AuthoringFormSchema extends Omit<FormSchema, "sections"> {
  sections: AuthoringSection[];
}

export type FormData = Record<string, unknown>;

export interface FormValidationIssue {
  path: string;
  message: string;
}

export interface FormValidationResult {
  valid: boolean;
  issues: FormValidationIssue[];
  /** Data restricted to known, visible fields with normalized values. */
  data: FormData;
  /** File object IDs referenced by attachment fields (server verifies existence, ownership and scan status). */
  attachmentIds: string[];
}
